import { BookOpen, CalendarDays, Home, LayoutGrid, Package, Settings, ShoppingBasket, User } from 'lucide-react';
import { useState, type ReactNode } from 'react';
import { hrefFor, navigate, type Route } from '../lib/router';
import { useGrocery } from '../lib/hooks';
import { useStore } from '../store/store';
import { Dialog, cx } from './ui';

const NAV: { route: Route; label: string; icon: typeof Home }[] = [
  { route: 'dashboard', label: 'Dashboard', icon: Home },
  { route: 'planner', label: 'Weekly Planner', icon: CalendarDays },
  { route: 'recipes', label: 'Recipes', icon: BookOpen },
  { route: 'grocery', label: 'Grocery List', icon: ShoppingBasket },
  { route: 'pantry', label: 'Pantry', icon: Package },
  { route: 'profile', label: 'My Profile', icon: User },
  { route: 'settings', label: 'Settings', icon: Settings },
];
const MOBILE: Route[] = ['dashboard', 'planner', 'grocery', 'recipes'];
const SHORT: Partial<Record<Route, string>> = { dashboard: 'Home', planner: 'Plan', grocery: 'Grocery', recipes: 'Recipes' };

export function Logo({ className }: { className?: string }) {
  return (
    <div className={cx('flex items-center gap-2.5', className)}>
      <svg width="30" height="30" viewBox="0 0 32 32" aria-hidden="true">
        <rect width="32" height="32" rx="9" className="fill-sage-600 dark:fill-sage-500" />
        <path d="M9.5 22.5c0-7.5 5.5-13 13-13 0 7.5-5.5 13-13 13z" className="fill-sage-50 dark:fill-ink-950" />
        <path d="M9.5 22.5 17 15" stroke="currentColor" strokeWidth="1.4" strokeLinecap="round" className="text-sage-600 dark:text-sage-500" />
      </svg>
      <span className="font-display text-lg font-semibold tracking-[0.18em] text-ink-900 dark:text-sand-50">NOURISH</span>
    </div>
  );
}

export function Layout({ route, children }: { route: Route; children: ReactNode }) {
  const [more, setMore] = useState(false);
  const isDemo = useStore((s) => s.isDemo);
  const { summary } = useGrocery();
  const remaining = summary.count - summary.done;

  return (
    <div className="min-h-screen lg:flex">
      {/* Desktop sidebar */}
      <aside className="no-print sticky top-0 hidden h-screen w-64 shrink-0 flex-col border-r border-sand-200 bg-sand-50/70 px-4 py-6 dark:border-white/5 dark:bg-ink-900/40 lg:flex">
        <Logo className="px-2" />
        <nav className="mt-8 flex flex-col gap-1" aria-label="Main">
          {NAV.map(({ route: r, label, icon: Icon }) => (
            <a key={r} href={hrefFor(r)} onClick={(e) => { e.preventDefault(); navigate(r); }} aria-current={route === r ? 'page' : undefined}
              className={cx('flex items-center gap-3 rounded-xl px-3 py-2.5 text-sm font-medium transition',
                route === r ? 'bg-white text-sage-800 shadow-soft dark:bg-white/10 dark:text-sage-200' : 'text-ink-700 hover:bg-white/70 dark:text-sand-200/80 dark:hover:bg-white/5')}>
              <Icon size={18} strokeWidth={1.8} />
              <span className="flex-1">{label}</span>
              {r === 'grocery' && remaining > 0 && <span className="rounded-full bg-sage-100 px-2 py-0.5 text-[11px] text-sage-800 dark:bg-sage-500/20 dark:text-sage-200">{remaining}</span>}
            </a>
          ))}
        </nav>
        <div className="mt-auto space-y-2 px-2 text-xs muted">
          {isDemo && <p className="rounded-lg bg-clay-50 px-2.5 py-2 text-clay-600 dark:bg-clay-500/10 dark:text-clay-300">You're exploring the demo profile. Edit My Profile or reset in Settings to start your own.</p>}
          <p>Plans are generated by a local rule-based engine. Prices &amp; nutrition are estimates.</p>
        </div>
      </aside>

      {/* Mobile header */}
      <header style={{ top: 'env(safe-area-inset-top, 0px)' }} className="no-print sticky top-0 z-30 flex items-center justify-between border-b border-sand-200/80 bg-sand-100/85 px-4 py-3 backdrop-blur dark:border-white/5 dark:bg-ink-950/85 lg:hidden">
        <Logo />
        {isDemo && <span className="rounded-full bg-clay-100 px-2.5 py-1 text-[11px] font-medium text-clay-600 dark:bg-clay-500/15 dark:text-clay-300">Demo</span>}
      </header>

      <main className="mx-auto w-full max-w-6xl flex-1 px-4 pb-28 pt-5 sm:px-6 lg:px-10 lg:pb-12 lg:pt-10">{children}</main>

      {/* Mobile bottom nav */}
      <nav aria-label="Primary" className="no-print fixed inset-x-0 bottom-0 z-40 border-t border-sand-200 bg-white/95 backdrop-blur dark:border-white/5 dark:bg-ink-900/95 lg:hidden" style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}>
        <div className="mx-auto grid max-w-md grid-cols-5">
          {MOBILE.map((r) => {
            const n = NAV.find((x) => x.route === r)!;
            const Icon = n.icon;
            return (
              <a key={r} href={hrefFor(r)} onClick={(e) => { e.preventDefault(); navigate(r); }} aria-current={route === r ? 'page' : undefined}
                className={cx('relative flex flex-col items-center gap-1 py-2.5 text-[11px] font-medium', route === r ? 'text-sage-700 dark:text-sage-300' : 'text-ink-700/60 dark:text-sand-200/50')}>
                <Icon size={21} strokeWidth={route === r ? 2.2 : 1.8} />
                {SHORT[r]}
                {r === 'grocery' && remaining > 0 && <span className="absolute right-[22%] top-1.5 h-2 w-2 rounded-full bg-clay-500" />}
              </a>
            );
          })}
          <button onClick={() => setMore(true)} className={cx('flex flex-col items-center gap-1 py-2.5 text-[11px] font-medium', ['pantry', 'profile', 'settings'].includes(route) ? 'text-sage-700 dark:text-sage-300' : 'text-ink-700/60 dark:text-sand-200/50')}>
            <LayoutGrid size={21} strokeWidth={1.8} />More
          </button>
        </div>
      </nav>
      <Dialog open={more} onClose={() => setMore(false)} title="More">
        <div className="grid gap-2 pb-2">
          {NAV.filter((n) => !MOBILE.includes(n.route)).map(({ route: r, label, icon: Icon }) => (
            <button key={r} onClick={() => { setMore(false); navigate(r); }} className={cx('flex items-center gap-3 rounded-xl px-3 py-3.5 text-left text-sm font-medium', route === r ? 'bg-sage-50 text-sage-800 dark:bg-sage-500/10 dark:text-sage-200' : 'hover:bg-sand-100 dark:hover:bg-white/5')}>
              <Icon size={19} /> {label}
            </button>
          ))}
        </div>
      </Dialog>
    </div>
  );
}
